#!/usr/bin/env python3
"""Install mycelium's commands as Codex skills.

Mycelium ships its skills as Claude Code plugin commands (`commands/*.md`).
Codex reads skills from `$CODEX_HOME/skills/<name>/SKILL.md`. The two formats
are close but not identical, so this script *generates* Codex skills rather
than copying or symlinking the command files:

1. **Frontmatter.** Claude commands carry only `description:`; Codex requires
   a `name:` as well. The name is derived from the filename
   (`commands/core.md` -> `mycelium-core`).
2. **Paths.** Command bodies reference helper scripts, templates, and
   references as bare relative paths (`skills/core/scripts/init_repo.py`).
   Claude resolves those against the plugin root; Codex has no equivalent
   root, so they are rewritten to absolute paths into this mycelium install.
3. **Enforcement.** Claude gets the post-action protocol enforced by hooks
   (SessionStart/PostToolUse/Stop). Codex has no hook system, so a preamble
   is injected stating the protocol as a self-enforced rule, along with the
   cross-tool concurrency contract. See `references/codex-parity.md`.

Because the output is fully derived from the source command file, `--check`
can regenerate in memory and diff against what is installed to detect drift.
No metadata sidecar is needed.

Usage:
    python install_codex_skills.py [--codex-home PATH] [--only NAME ...]
    python install_codex_skills.py --check
    python install_codex_skills.py --uninstall
"""

from __future__ import annotations

import argparse
import os
import re
import shutil
import sys
from pathlib import Path

SKILL_PREFIX = "mycelium-"

# Marks generated files so a human landing in ~/.codex/skills knows not to edit
# them by hand. Kept out of the frontmatter so Codex never has to parse it.
GENERATED_BANNER = (
    "<!-- Generated by mycelium's install_codex_skills.py from {source}.\n"
    "     Do not edit here; edit the mycelium source and re-run the installer. -->"
)


def mycelium_root() -> Path:
    """Repo root of this mycelium install (scripts/ -> core/ -> skills/ -> root)."""
    return Path(__file__).resolve().parent.parent.parent.parent


def codex_home() -> Path:
    """Codex's config root. Honours $CODEX_HOME, as Codex itself does."""
    env = os.environ.get("CODEX_HOME")
    return Path(env).expanduser() if env else Path.home() / ".codex"


def split_frontmatter(text: str) -> tuple[str, str]:
    """Split a markdown file into (frontmatter_body, markdown_body).

    Returns ("", text) when there is no frontmatter. Deliberately hand-rolled
    rather than using pyyaml: the only field that matters is `description`,
    and keeping this dependency-free means the Codex bridge installs even in
    an environment where mycelium's optional yaml dependency is absent.
    """
    if not text.startswith("---\n"):
        return "", text
    end = text.find("\n---\n", 4)
    if end == -1:
        return "", text
    return text[4:end], text[end + 5 :]


def parse_description(frontmatter: str) -> str:
    """Extract `description:` from frontmatter, handling folded block scalars.

    Supports both the inline form (`description: text`) and the folded form
    used by mycelium's commands:

        description: >
          line one
          line two

    Folded scalars join with spaces, per YAML. Quotes around an inline value
    are stripped so the value can be re-emitted safely.
    """
    lines = frontmatter.split("\n")
    for i, line in enumerate(lines):
        if not line.startswith("description:"):
            continue
        inline = line[len("description:") :].strip()
        if inline not in (">", "|", ">-", "|-", ">+", "|+"):
            return inline.strip("\"'")
        fold = inline.startswith(">")
        collected: list[str] = []
        for cont in lines[i + 1 :]:
            if cont.strip() and not cont.startswith((" ", "\t")):
                break  # dedented back to a sibling key
            collected.append(cont.strip())
        joined = " ".join(c for c in collected if c) if fold else "\n".join(collected)
        return joined.strip()
    return ""


def rewrite_paths(body: str, root: Path) -> str:
    """Absolutise mycelium-relative paths so they resolve outside the plugin.

    Rewrites `skills/core/...` to `<root>/skills/core/...`. Only matches when
    the reference starts at a non-path character, so an already-absolute path
    (`/opt/mycelium/skills/core/x.py`) is left alone and never doubled up.
    """
    return re.sub(
        r"(?<![\w/.-])(skills/core/[\w./-]+)",
        lambda m: f"{root}/{m.group(1)}",
        body,
    )


def rewrite_command_refs(body: str, known: set[str]) -> str:
    """Rewrite Claude command references to their Codex skill names.

    `/mycelium:review` -> `mycelium-review`, but only for commands that
    actually ship, so prose mentioning an unshipped name is left intact.
    """
    return re.sub(
        r"/mycelium:([a-z][a-z0-9-]*)",
        lambda m: (
            f"{SKILL_PREFIX}{m.group(1)}"
            if f"{SKILL_PREFIX}{m.group(1)}" in known
            else m.group(0)
        ),
        body,
    )


def codex_preamble(root: Path) -> str:
    """The parity preamble injected into every generated Codex skill.

    This is the load-bearing part of the bridge. Under Claude the post-action
    protocol is enforced by hooks that fire whether or not the model
    cooperates; under Codex nothing fires, so the same protocol has to be
    stated as an instruction the agent follows itself.
    """
    return f"""## Running under Codex

You are running this mycelium skill under Codex, not Claude Code. Two
differences change what you must do:

**1. No hooks fire.** Under Claude Code, mycelium's hooks open a session log
at session start, track file edits, and can block session end if substantial
work happened without `.living/` being updated. None of that machinery exists
here. The post-action protocol is therefore **yours to enforce**: after any
substantial piece of work, log non-obvious choices to `.living/decisions.md`,
surprises to `.living/learnings.md`, and write the session summary. Do it
because nothing else will.

**2. A Claude chat may be working in this repo at the same time.** `.living/`
is shared across every agent in the working tree. Before any read-modify-write
of a shared file, take the lock:

| Task | Use |
|------|-----|
| Claim a `YYYY-MM-DD-NNN` session-log slot | `python3 {root}/skills/core/scripts/allocate_session_slot.py` |
| Upsert a row in a markdown **table** registry (LOG/FINDINGS/TODO) | `python3 {root}/skills/core/scripts/upsert_manifest_row.py` |
| Upsert a `LOG_REGISTRY.md` row | `python3 {root}/skills/core/scripts/upsert_registry_row.py` |
| Wrap your own critical section | `mycelium_locks.file_lock()` from `{root}/skills/core/scripts/` |

Never hand-edit a table registry with an editor tool. A Claude chat holding
the flock will not see your write, and one of the two rows is silently lost.

Append-only files — `.living/learnings.md`, `.living/decisions.md`,
`.living/conventions.md` — are safe to append to without a lock; POSIX
`O_APPEND` never overwrites. At worst entries interleave.

Full contract: `{root}/skills/core/references/concurrency.md` and
`{root}/skills/core/references/codex-parity.md`.

---
"""


def build_skill(source: Path, root: Path, known: set[str]) -> str:
    """Generate the Codex SKILL.md text for one mycelium command file."""
    raw = source.read_text(encoding="utf-8")
    frontmatter, body = split_frontmatter(raw)
    description = parse_description(frontmatter)
    if not description:
        raise ValueError(f"{source.name}: no description in frontmatter")

    name = SKILL_PREFIX + source.stem
    body = rewrite_paths(body, root)
    body = rewrite_command_refs(body, known)

    # Codex reads the description from a single YAML line; fold any newlines
    # and escape quotes so the frontmatter stays parseable.
    flat = " ".join(description.split()).replace('"', '\\"')

    banner = GENERATED_BANNER.format(source=f"commands/{source.name}")
    return (
        f"---\nname: {name}\ndescription: \"{flat}\"\n---\n\n"
        f"{banner}\n\n{codex_preamble(root)}\n{body.lstrip()}"
    )


def discover(root: Path, only: list[str] | None) -> list[Path]:
    """Command files to install, filtered by --only if given."""
    commands = sorted((root / "commands").glob("*.md"))
    if not commands:
        raise FileNotFoundError(f"No commands found under {root / 'commands'}")
    if only:
        wanted = {o.removeprefix(SKILL_PREFIX) for o in only}
        commands = [c for c in commands if c.stem in wanted]
        missing = wanted - {c.stem for c in commands}
        if missing:
            raise ValueError(f"Unknown command(s): {', '.join(sorted(missing))}")
    return commands


def install(root: Path, dest_root: Path, only: list[str] | None) -> int:
    sources = discover(root, only)
    known = {SKILL_PREFIX + s.stem for s in sources}
    dest_root.mkdir(parents=True, exist_ok=True)
    for source in sources:
        name = SKILL_PREFIX + source.stem
        target = dest_root / name / "SKILL.md"
        target.parent.mkdir(parents=True, exist_ok=True)
        content = build_skill(source, root, known)
        unchanged = target.exists() and target.read_text(encoding="utf-8") == content
        target.write_text(content, encoding="utf-8")
        print(f"  {'unchanged' if unchanged else 'installed'}: {name}")
    print(f"\n{len(sources)} skill(s) in {dest_root}")
    return 0


def check(root: Path, dest_root: Path, only: list[str] | None) -> int:
    """Report drift between installed skills and what mycelium would generate."""
    sources = discover(root, only)
    known = {SKILL_PREFIX + s.stem for s in sources}
    missing, stale = [], []
    for source in sources:
        name = SKILL_PREFIX + source.stem
        target = dest_root / name / "SKILL.md"
        if not target.exists():
            missing.append(name)
        elif target.read_text(encoding="utf-8") != build_skill(source, root, known):
            stale.append(name)
    for n in missing:
        print(f"  MISSING: {n}")
    for n in stale:
        print(f"  STALE:   {n}")
    if not missing and not stale:
        print(f"  All {len(sources)} skill(s) current in {dest_root}")
        return 0
    print("\nRun without --check to (re)install.")
    return 1


def uninstall(dest_root: Path) -> int:
    """Remove every mycelium-owned skill directory, leaving others alone."""
    if not dest_root.exists():
        print(f"  Nothing to remove: {dest_root} does not exist")
        return 0
    removed = 0
    for entry in sorted(dest_root.iterdir()):
        if entry.is_dir() and entry.name.startswith(SKILL_PREFIX):
            shutil.rmtree(entry)
            print(f"  removed: {entry.name}")
            removed += 1
    print(f"\n{removed} skill(s) removed from {dest_root}")
    return 0


def parse_args():
    parser = argparse.ArgumentParser(
        description="Install mycelium's commands as Codex skills."
    )
    parser.add_argument(
        "--codex-home",
        type=Path,
        default=None,
        help="Codex config root (default: $CODEX_HOME, else ~/.codex)",
    )
    parser.add_argument(
        "--only",
        nargs="+",
        metavar="NAME",
        help="Install only these commands (e.g. core review, or mycelium-core)",
    )
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument(
        "--check",
        action="store_true",
        help="Report drift without writing; exit 1 if anything is missing or stale",
    )
    mode.add_argument(
        "--uninstall",
        action="store_true",
        help="Remove all mycelium-* skills from the Codex skills directory",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    root = mycelium_root()
    dest_root = (args.codex_home or codex_home()) / "skills"

    if args.uninstall:
        return uninstall(dest_root)
    if args.check:
        return check(root, dest_root, args.only)
    return install(root, dest_root, args.only)


if __name__ == "__main__":
    sys.exit(main())
